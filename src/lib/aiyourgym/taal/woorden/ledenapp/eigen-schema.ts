/** Een titel uit het voorstel in de taal van het lid; een eigen titel blijft zoals hij is. */
export function dagTitelIn(titel: string, boek: { dagTitels: Record<string, string> }): string {
  return Object.prototype.hasOwnProperty.call(boek.dagTitels, titel) ? boek.dagTitels[titel] : titel
}
